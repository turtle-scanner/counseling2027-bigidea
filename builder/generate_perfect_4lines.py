# UPDATE data.js WITH 4-LINE MODEL ANSWERS
# =============================================================================
def update_data_js():
    with open(DATA_JS_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    prefix = '// 2027 전문상담 임용고시 핵심 교재 데이터베이스\nconst TEXTBOOK_DATA = '
    suffix = ';\n'

    json_str = content.replace(prefix, '').rstrip(';\n \t\r')
    data = json.loads(json_str)

    updated_count = 0
    total_count = 0

    for subject in data:
        for topic in subject['topics']:
            total_count += 1
            t_id = topic['id']
            if t_id in ANSWERS:
                item = ANSWERS[t_id]
                topic['templateAnswer'] = {
                    'question': item['question'],
                    'lines': item['lines'],
                    'structure': '\n'.join(item['lines'])
                }
                updated_count += 1
            else:
                print(f"[WARNING] Missing 4-line answer for: {t_id}")

    print(f"Total topics in data.js: {total_count}")
    print(f"Successfully updated with 4-line answers: {updated_count}")

    new_content = prefix + json.dumps(data, ensure_ascii=False, indent=2) + suffix

    with open(DATA_JS_PATH, 'w', encoding='utf-8') as f:
        f.write(new_content)

    print(f"data.js successfully written! Size: {os.path.getsize(DATA_JS_PATH):,} bytes")

if __name__ == '__main__':
    update_data_js()



